"""Reproducible demonstration scenarios.

Runs every scenario through the real BatteryX API (in-memory database, no external services, no AI calls)
and writes:
  docs/demo_results.json   raw API responses (KPIs, checks, comparison) per scenario
  docs/DEMO_RESULTS.md      generated tables (every number comes from the API response)

    python -I scripts/demo_scenarios.py

All inputs are the stage-1 ILLUSTRATIVE example values (not a real cell datasheet) plus the stated
scenario changes. Results are model ESTIMATES. Running the script again gives identical numbers.
"""
from __future__ import annotations

import copy
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.stdout.reconfigure(encoding="utf-8")

from fastapi.testclient import TestClient  # noqa: E402

from app.config import Settings  # noqa: E402
from app.main import create_app  # noqa: E402

DOCS = ROOT.parent / "docs"
c = TestClient(create_app("sqlite://", settings=Settings(db_backend="sql", database_url="sqlite://")))
ex = c.get("/api/v1/examples/designs").json()
REQS = ex["designs"][0]["requirements"]
A, B, C = (copy.deepcopy(d) for d in ex["designs"])


def evaluate(d):
    r = c.post("/api/v1/designs/evaluate", json=d)
    assert r.status_code == 200, r.text
    return r.json()


def checks(r, only_issues=True):
    cs = r["modules"]["bms"]["values"]["checks"]
    return [x for x in cs if not only_issues or x["status"] != "PASS"]


scenarios = []


def add(sid, title, purpose, changes, design):
    r = evaluate(design)
    scenarios.append({"id": sid, "title": title, "purpose": purpose, "changes": changes, "result": r})
    return r


add("S1", "Baseline A: 4S1P, 10 A charge, passive cooling", "Reference design from stage 1", "none", A)
add("S2", "Alternative B: 1C charge with heat spreader", "Faster charging; shows the C-rate warning at the cell limit", "charge 20 A, spreader R_th 3 K/W (+0.08 kg/cell)", B)
add("S3", "Alternative C: 4S2P", "More energy and lower per-cell current; shows the mass trade-off", "parallel = 2, charge 20 A, 4 sensors", C)
hot = copy.deepcopy(A); hot["name"] = "A @ 44 °C ambient"; hot["operating"]["ambient_c"] = 44
add("S4", "Thermal stress: baseline at 44 °C ambient", "Temperature limit check and charge-current derating (CT-01)", "ambient 35 → 44 °C", hot)
prot = copy.deepcopy(A); prot["name"] = "A with mis-coordinated protection"; prot["operating"]["charge_current_a"] = 22; prot["limits"]["fuse_rating_a"] = 20
add("S5", "Protection mis-coordination", "Fuse rated below the BMS limit and below the charge current", "charge 22 A, fuse 30 → 20 A (BMS 25 A)", prot)
minimal = {"name": "Minimal cell data", "series": 4, "parallel": 1, "requirements": REQS,
           "cell": {"id": "USER-MINIMAL", "chemistry": "LFP", "nominal_voltage_v": 3.2, "capacity_ah": 20, "data_status": "user_entered"},
           "operating": {"ambient_c": 35, "soc_min_pct": 10, "soc_max_pct": 90, "charge_current_a": 10}}
add("S6", "Missing datasheet data", "Shows that missing inputs are flagged, never invented", "inline cell with only V_nom and capacity", minimal)

cmp = c.post("/api/v1/designs/compare", json={"baseline": A, "alternatives": [B, C]}).json()
var = c.post("/api/v1/variation", json={"design": C, "variation": {"samples": 2000, "capacity_tolerance_pct": 3, "resistance_tolerance_pct": 15, "seed": 7}}).json()
sweep = []
for i_ch in (5, 10, 15, 20, 25):
    d = copy.deepcopy(A); d["operating"]["charge_current_a"] = i_ch; d["name"] = f"A @ {i_ch} A"
    r = evaluate(d)
    sweep.append({"charge_current_a": i_ch, "c_rate": r["kpis"]["charge_c_rate"], "charge_time_cc_h": r["kpis"]["charge_time_cc_estimate_h"],
                  "peak_temp_c": r["kpis"]["peak_cell_temp_charge_c"],
                  "status": {x["id"]: x["status"] for x in r["modules"]["bms"]["values"]["checks"] if x["id"] in ("EL-01", "TH-01", "PR-01", "PR-02", "CT-01")}})

out = {"generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"), "api_version": c.get("/health").json()["version"],
       "note": "Illustrative stage-1 inputs; model estimates, not measurements.",
       "scenarios": scenarios, "comparison_S7": cmp, "variation_S8": var, "sweep_S9": sweep}
DOCS.mkdir(exist_ok=True)
(DOCS / "demo_results.json").write_text(json.dumps(out, indent=1, ensure_ascii=False), encoding="utf-8")

# ---------------------------------------------------------------- generated markdown
f = lambda x, d=4: "—" if x is None else (f"{x:.{d}g}" if isinstance(x, float) else str(x))  # noqa: E731
L = ["# Demonstration results (generated)", "",
     f"Generated by `backend/scripts/demo_scenarios.py` on {out['generated_at']} against API v{out['api_version']}. "
     "**Every number below is copied programmatically from the API response.** Inputs are the stage-1 **illustrative** values "
     "(cell `EXAMPLE-LFP-20AH` is not a real product); results are **model estimates, not measurements**. Re-running the script reproduces them exactly.", "",
     "## Scenario KPIs", "",
     "| Id | Scenario | Usable energy [Wh] | CC charge time [h] | Peak cell temp, charge [°C] | Max safe charge current [A] | Mass [kg] | Volume [L] | Rel. cost | Checks FAIL/WARN/NOT_EVAL | Requirements not met |",
     "|---|---|---|---|---|---|---|---|---|---|---|"]
for s in scenarios:
    k, r = s["result"]["kpis"], s["result"]
    sm = r["safety_summary"]
    nm = [q["id"] for q in r["requirements"] if q["status"] == "NOT_MET"]
    L.append(f"| {s['id']} | {s['title']} | {f(k['usable_energy_wh'])} | {f(k['charge_time_cc_estimate_h'])} | {f(k.get('peak_cell_temp_charge_c'))} | "
             f"{f(k.get('max_safe_charge_current_a'))} | {f(k.get('module_mass_kg'))} | {f(k.get('module_volume_l'))} | {f(k.get('relative_cost_index'))} | "
             f"{sm['FAIL']}/{sm['WARN']}/{sm['NOT_EVALUATED']} | {', '.join(nm) or 'none'} |")
L += ["", "## Safety findings per scenario (non-PASS checks)", ""]
for s in scenarios:
    L.append(f"**{s['id']} {s['title']}**: change: {s['changes']}. Purpose: {s['purpose']}.")
    L += [f"- `{x['id']}` {x['status']}: {x['description']} ({x['detail']})" for x in checks(s["result"]) if x["status"] in ("FAIL", "WARN")] or ["- no FAIL/WARN"]
    ne = [x["id"] for x in checks(s["result"]) if x["status"] == "NOT_EVALUATED"]
    if ne:
        L.append(f"- not evaluated (missing inputs): {', '.join(ne)}")
    unsup = sorted({fl["code"] for fl in s["result"]["flags"] if fl["severity"] in ("unsupported", "missing_input")})
    L.append(f"- flags (missing / unsupported): {', '.join(unsup) or 'none'}")
    L.append("")
L += ["## S7 Comparison A / B / C (default weights)", "",
      "Ranking = weighted score − 0.5 × (requirements not met); designs with a safety FAIL are not eligible.", "",
      "| Rank | Design | Eligible | Weighted score | Rank value | Requirements not met | Safety warnings |", "|---|---|---|---|---|---|---|"]
for r in sorted(cmp["ranking"], key=lambda r: r.get("rank") or 99):
    L.append(f"| {r.get('rank', '—')} | {r['design_name']} | {r['eligible']} | {f(r['score'])} | {f(r['rank_value'])} | {'; '.join(r['requirements_not_met']) or 'none'} | {'; '.join(r['safety_warnings']) or 'none'} |")
rec = cmp["recommendation"]
L += ["", f"**Engine recommendation:** {rec['design_name']}. Why: " + "; ".join(rec["why"]) + ". Trade-offs: " + "; ".join(rec["trade_offs"]) + ".", "",
      f"Notes: {' '.join(cmp['notes'])}", "",
      "## S8 Cell-to-cell variation, design C (2000 builds, ±3 % capacity, ±15 % resistance as 3σ, seed 7)", "",
      "| Quantity | p5 | p50 | p95 | max |", "|---|---|---|---|---|"]
for key, label in [("usable_energy_wh", "Usable energy [Wh]"), ("max_cell_current_share_pct", "Highest parallel current share [%]"),
                   ("worst_cell_temp_charge_c", "Worst-cell temperature, charge [°C]"), ("cell_temp_spread_k", "Cell temperature spread [K]")]:
    q = var["values"][key]
    L.append(f"| {label} | {f(q['p5'])} | {f(q['p50'])} | {f(q['p95'])} | {f(q['max'])} |")
L += ["", "## S9 Charge-current sweep on baseline A", "", "| Charge current [A] | C-rate | CC charge time [h] | Peak temp [°C] | EL-01 | TH-01 | PR-01 | PR-02 | CT-01 |", "|---|---|---|---|---|---|---|---|---|"]
for row in sweep:
    st = row["status"]
    L.append(f"| {row['charge_current_a']} | {f(row['c_rate'])} | {f(row['charge_time_cc_h'])} | {f(row['peak_temp_c'])} | {st['EL-01']} | {st['TH-01']} | {st['PR-01']} | {st['PR-02']} | {st['CT-01']} |")
L += ["", "## S10 AI claim verification", "",
      "The copilot's verifier is exercised offline in `backend/tests/test_copilot.py` (ten incorrect-claim cases, e.g. an invented cycle life, "
      "a mismatched temperature, a certification statement, an invented cell part number, an invented datasheet URL; all are flagged). "
      "No live Claude transcript is included here because no Anthropic API key was configured when this file was generated.", ""]
(DOCS / "DEMO_RESULTS.md").write_text("\n".join(L), encoding="utf-8")
print("\n".join(L[:20]))
print(f"... written {DOCS / 'DEMO_RESULTS.md'} and demo_results.json")
